def resolve_recipe_nlg_path(path: str | Path | None = None) -> Path:
    if path is not None:
        return Path(path)
    for candidate in RECIPE_NLG_PATH_CANDIDATES:
        if candidate.exists():
            return candidate
    return RECIPE_NLG_PATH_CANDIDATES[0]


